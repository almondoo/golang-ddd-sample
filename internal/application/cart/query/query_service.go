package query

import "context"

// CartQueryService はカートの参照専用の問い合わせを表すポートである。
//
// cart.Repository（ドメイン層）が「集約を読み書きする」ためのインターフェース
// であるのに対し、こちらは「画面表示に必要な形へ加工済みのデータを返す」
// ためのインターフェースである。両者を分けているのは CQRS
// （コマンドとクエリの責務分離）の考え方に基づく。クエリ側はドメイン
// モデルの不変条件を守る必要がなく、複数コンテキストのテーブルを
// 自由に JOIN してよいという緩い制約のもとで実装できる。
type CartQueryService interface {
	// FindByCustomerID は指定顧客のカートを DTO として取得する。
	//
	// カートが存在しない場合や、存在するが明細が 0 件の場合のどちらも、
	// エラーではなく空の CartDTO（Items が空スライス、TotalAmount が 0）を
	// 返す。カートというドメイン概念にとって「カートがまだ作られていない」
	// ことと「カートは作られたが中身が空」ことは、読み手（利用者）から見た
	// 意味としては同じ「今は何も入っていない」であり、区別する価値がない。
	// これを区別してエラーとして扱ってしまうと、呼び出し側（画面）が
	// 毎回「404 かもしれないので特別扱いする」という不要な分岐を
	// 持たされることになる。
	FindByCustomerID(ctx context.Context, customerID string) (*CartDTO, error)
}
